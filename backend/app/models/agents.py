"""
Pydantic Schemas for LangGraph RAG Agent, Security Auditor & Multi-Agent Operations.
"""

from typing import Any, List, Optional
from pydantic import BaseModel, Field


class SecurityCheckRequest(BaseModel):
    query: str = Field(..., min_length=1, description="Query text to check for prompt injection or jailbreak patterns")


class SecurityCheckResult(BaseModel):
    is_safe: bool = Field(..., description="Whether the query passed rule-based security checks")
    risk_level: str = Field(..., description="Assessed risk level: 'none' | 'low' | 'medium' | 'high'")
    flagged_patterns: List[str] = Field(
        default_factory=list,
        description="List of detected security threat descriptions"
    )
    reason: str = Field(..., description="Detailed explanation of the security audit assessment")


class RAGAskRequest(BaseModel):
    query: str = Field(..., min_length=1, description="User question or query text")
    department_filter: Optional[str] = Field(
        default=None,
        description="Optional department name for ChromaDB & BM25 pre-filtering"
    )


class CitationItem(BaseModel):
    filename: str = Field(..., description="Source document filename")
    department: str = Field(..., description="Department owner of the document")
    chunk_index: int = Field(..., description="Index of the specific chunk used")


class RAGAskResponse(BaseModel):
    query: str = Field(..., description="Original user query")
    department_filter: Optional[str] = Field(default=None, description="Department pre-filter applied")
    answer: str = Field(..., description="Grounded answer generated by local LLM or security rejection message")
    citations: list[CitationItem] = Field(default_factory=list, description="List of source document citations")
    retrieved_chunks: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Raw retrieved context chunks for transparency & debugging"
    )
    security_check: SecurityCheckResult = Field(
        ...,
        description="Rule-based pre-retrieval security audit validation result for auditability and transparency"
    )
